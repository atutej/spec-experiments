#!/usr/bin/env python
"""Build held-out rollout prompts for measuring a drafter's acceptance length on the TARGET model's own generations.

The trainer's `eal` is teacher-forced on dataset text. To measure acceptance on what the target model actually writes, we need
prompts, let the target generate, and read vLLM's speculative-decoding counters (see run_eval.py). This script makes the prompts:

  - conversations: held out, i.e. NOT in the 100k training sample (the trainer's own validation split is by rows, so turns of one
    conversation sit in both train and validation); chosen with a fixed seed.
  - per conversation, two prompts, each a conversation prefix rendered with the target's chat template up to a generation prompt:
      first_turn : the first assistant turn (fully on-policy: the context is just the task)
      later_turn : one uniformly random later assistant turn (the context is the corpus's own earlier turns and terminal
                   outputs, teacher-forced; only the next turn is generated by the target)
  - only prompts of at most --max-prompt-tokens tokens (so prompt + generation fits the trainer's 16384-token window).

Output (in --out-dir): first_turn.jsonl, later_turn.jsonl (one JSON object per line with a `prompt` text column plus metadata),
manifest.json (sources, seed, counts, sha256 of the files).
"""
import argparse
import hashlib
import importlib.util
import json
import random
import sys
from pathlib import Path

import pyarrow.parquet as pq

TOOLS = Path(__file__).resolve().parents[1]
KEY_COLS = ("trial_name", "episode")


def load_exporter():
    spec = importlib.util.spec_from_file_location("export_registry_dataset", TOOLS / "export_registry_dataset.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sample_keys(path: str) -> set[tuple]:
    """(trial_name, episode) of every conversation of the training sample."""
    keys = set()
    with open(path, encoding="utf-8") as f:  # iterate the file object: U+2028 appears inside records
        for line in f:
            r = json.loads(line)
            keys.add((r["trial_name"], str(r["episode"])))
    return keys


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--exclude-sample", required=True, help="the training sample JSONL (its conversations are excluded)")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--conversations", type=int, default=500)
    ap.add_argument("--max-prompt-tokens", type=int, default=8000)
    ap.add_argument("--model", default="Qwen/Qwen3-0.6B", help="target model: its tokenizer and chat template render the prompts")
    ap.add_argument("--dataset", default="nemotron-terminal", help="speculators dataset preset")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    from speculators.data_generation.configs import DATASET_CONFIGS
    from transformers import AutoTokenizer

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    exp = load_exporter()
    cfg = DATASET_CONFIGS[args.dataset]
    files = exp.resolve_parquet_files(cfg.hf_path, cfg.subset, cfg.split)

    print("excluded sample:", args.exclude_sample, flush=True)
    excluded = sample_keys(args.exclude_sample)
    print(f"  {len(excluded)} conversations in the training sample", flush=True)

    # pass 1: the key of every row of the corpus (two columns only, cheap)
    positions = {}  # key -> (file index, row index)
    total = 0
    for fi, f in enumerate(files):
        row = 0
        for batch in pq.ParquetFile(f).iter_batches(batch_size=4096, columns=list(KEY_COLS)):
            for t, e in zip(batch.column("trial_name").to_pylist(), batch.column("episode").to_pylist()):
                positions.setdefault((t, str(e)), (fi, row))
                row += 1
        total += row
    heldout = sorted(k for k in positions if k not in excluded)
    print(f"corpus rows {total}, distinct keys {len(positions)}, held out (not in the sample): {len(heldout)}", flush=True)

    rng = random.Random(args.seed)
    order = rng.sample(heldout, len(heldout))  # a seeded shuffle; we walk it until we have enough usable conversations
    want_per_file = {}
    for k in order[: int(args.conversations * 2.0)]:  # oversample: some conversations have no usable later turn
        fi, ri = positions[k]
        want_per_file.setdefault(fi, {})[ri] = k
    n_candidates = sum(len(v) for v in want_per_file.values())

    # pass 2: read the candidate conversations in full
    convs = {}
    for fi, rows in want_per_file.items():
        row, remaining = 0, set(rows)
        for batch in pq.ParquetFile(files[fi]).iter_batches(batch_size=256, columns=["conversations", *KEY_COLS]):
            n = batch.num_rows
            hit = [i for i in range(n) if (row + i) in rows]
            if hit:
                for i, d in zip(hit, batch.take(hit).to_pylist()):
                    convs[rows[row + i]] = d["conversations"]
                    remaining.discard(row + i)
            row += n
            if not remaining:
                break  # every wanted row of this file has been read
    print(f"read {len(convs)} of {n_candidates} candidate conversations", flush=True)

    tok = AutoTokenizer.from_pretrained(args.model)

    def render(msgs):
        text = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True, enable_thinking=True)
        ids = tok(text, add_special_tokens=False)["input_ids"]
        return text, len(ids)

    first, later = [], []
    n_conv = 0
    for key in order:
        if key not in convs:
            continue
        if len(first) >= args.conversations and len(later) >= args.conversations:
            break
        msgs = [{"role": m["role"], "content": m["content"]} for m in convs[key]]
        turns = [j for j, m in enumerate(msgs) if m["role"] == "assistant" and j > 0]
        if not turns:
            continue
        n_conv += 1
        rows = {}
        for j in turns:
            text, n = render(msgs[:j])
            if n <= args.max_prompt_tokens:
                rows[j] = {"prompt": text, "conversation": list(key), "turn_index": j, "assistant_turn": turns.index(j),
                           "prompt_tokens": n}
        if turns[0] in rows and len(first) < args.conversations:
            first.append({**rows[turns[0]], "turn_kind": "first"})
        later_choices = [j for j in rows if j != turns[0]]
        if later_choices and len(later) < args.conversations:
            j = random.Random(f"{args.seed}:{key}").choice(sorted(later_choices))
            later.append({**rows[j], "turn_kind": "later"})

    manifest = {"seed": args.seed, "model": args.model, "dataset": args.dataset, "max_prompt_tokens": args.max_prompt_tokens,
                "excluded_sample": args.exclude_sample, "excluded_conversations": len(excluded),
                "heldout_pool": len(heldout), "conversations_scanned": n_conv, "files": {}}
    for name, rows in (("first_turn", first), ("later_turn", later)):
        p = out / f"{name}.jsonl"
        with open(p, "w", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        toks = sorted(r["prompt_tokens"] for r in rows)
        manifest["files"][name] = {"prompts": len(rows), "sha256": sha256(p),
                                   "prompt_tokens_median": toks[len(toks) // 2] if toks else None,
                                   "prompt_tokens_max": toks[-1] if toks else None,
                                   "assistant_turn_histogram": {str(t): sum(1 for r in rows if r["assistant_turn"] == t)
                                                                for t in sorted({r["assistant_turn"] for r in rows})}}
    overlap = {tuple(r["conversation"]) for r in first + later} & excluded
    manifest["overlap_with_training_sample"] = len(overlap)
    json.dump(manifest, open(out / "manifest.json", "w"), indent=2)
    print(json.dumps(manifest, indent=2))
    if overlap:
        sys.exit("BUG: prompts overlap with the training sample")


if __name__ == "__main__":
    main()
