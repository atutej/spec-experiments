"""Turn tokenized Datakit rows (token ids rendered with the Grug chat template) back into chat messages + tools, for `speculators regenerate-responses`.

The dataset rows were rendered with the target's chat template, which is invertible: decode the ids, split at the role headers, read the system header
(reasoning mode, tools block with one JSON tool per line), user turns, assistant turns (optional <|start_think|> reasoning, text, <tool_call> blocks) and
tool results (<tool_response name="...">...</tool_response>). `roundtrip_ok` re-renders the parsed conversation with the tokenizer's own chat template and
compares it with the original text, so a row is only used when the conversion is exact.

  python rows_to_messages.py check --dataset DIR --num 300          # round-trip rate on a sample of rows
"""
import argparse
import json
import re

HDR = re.compile(r"<\|start_header_id\|>(\w+)<\|end_header_id\|>")
CALL = re.compile(r"<tool_call>\n(\{.*?\})\n</tool_call>", re.S)
RESP = re.compile(r'^<tool_response(?: name="([^"]*)")?>(.*)</tool_response>$', re.S)
END_OF_TEXT = " <|end_of_text|>"
TOOLS = re.compile(r"<tools>\n(.*?)\n</tools>", re.S)


def parse_text(text: str) -> dict:
    """Decoded row text -> {"messages", "tools", "enable_thinking"}."""
    bos = "<|begin_of_text|>"
    assert text.startswith(bos), "row does not start with the BOS token"
    body = text[len(bos):]
    if body.endswith(END_OF_TEXT):            # the dataset appends this document marker after the conversation
        body = body[: -len(END_OF_TEXT)]
    parts = HDR.split(body)                 # ['', role, content, role, content, ...]
    assert parts[0] == "", "text before the first header"
    messages, tools, thinking = [], None, None
    call_n = 0
    for role, raw in zip(parts[1::2], parts[2::2]):
        if raw.endswith("<|eot_id|>\n"):
            content = raw[: -len("<|eot_id|>\n")]
        elif raw.endswith("<|eot_id|>"):
            content = raw[: -len("<|eot_id|>")]
        else:
            content = raw                    # an unfinished last turn (a row clipped inside it)
        if role != "system" and content.startswith("\n"):
            content = content[1:]                # the newline that belongs to the header line
        if role == "system" and not messages and thinking is None:
            m = re.match(r"Reasoning: (/think|/nothink)", content)
            if m:
                thinking = m.group(1) == "/think"
            blk = TOOLS.search(content)
            if blk:
                tools = [json.loads(line) for line in blk.group(1).split("\n") if line.strip()]
            # the whole auxiliary header is regenerated by the template from the reasoning mode and the tools; custom instructions are not used by this dataset
            continue
        if role == "assistant":
            reasoning = None
            if content.startswith("<|start_think|>") and "<|end_think|>" in content:
                reasoning, content = content[len("<|start_think|>"):].split("<|end_think|>", 1)
            calls = []
            first = content.find("<tool_call>")
            text_part = content if first < 0 else content[:first]
            for blk in CALL.findall(content if first >= 0 else ""):
                name = json.loads(blk)["name"]
                args_raw = blk[blk.index('"arguments": ') + len('"arguments": '): blk.rindex("}")]
                calls.append({"id": f"call_{call_n}", "type": "function", "function": {"name": name, "arguments": args_raw}})
                call_n += 1
            msg = {"role": "assistant", "content": text_part}
            if reasoning is not None:
                msg["reasoning_content"] = reasoning
            if calls:
                msg["tool_calls"] = calls
            messages.append(msg)
        elif role == "tool":
            m = RESP.match(content)
            if not m:
                messages.append({"role": "tool", "content": content}); continue
            msg = {"role": "tool", "content": m.group(2)}
            if m.group(1):
                msg["name"] = m.group(1)
            messages.append(msg)
        else:
            messages.append({"role": role, "content": content})
    return {"messages": messages, "tools": tools, "enable_thinking": thinking}


def render(tok, conv: dict) -> str:
    kw = {}
    if conv["enable_thinking"] is not None:
        kw["enable_thinking"] = conv["enable_thinking"]
    return tok.apply_chat_template(conv["messages"], tools=conv["tools"], tokenize=False, **kw)


def roundtrip_ok(tok, ids: list[int]) -> tuple[bool, str]:
    text = tok.decode(ids, skip_special_tokens=False)
    try:
        conv = parse_text(text)
        again = render(tok, conv)
    except Exception as e:  # noqa: BLE001
        return False, f"parse/render error: {type(e).__name__}: {str(e)[:80]}"
    if text.endswith(END_OF_TEXT):
        again += END_OF_TEXT
        text_cmp = text
    else:
        text_cmp = text
    if not text_cmp.rstrip("\n").endswith("<|eot_id|>") and not text_cmp.endswith(END_OF_TEXT):   # a row clipped inside its last turn has no closing token
        again = again.rstrip("\n")
        if again.endswith("<|eot_id|>"):
            again = again[: -len("<|eot_id|>")]
    if again == text:
        return True, "exact"
    n = next((i for i, (a, b) in enumerate(zip(again, text)) if a != b), min(len(again), len(text)))
    return False, f"differs at char {n}: rendered {again[max(0, n-30):n+40]!r} vs original {text[max(0, n-30):n+40]!r}"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check"); c.add_argument("--dataset", required=True); c.add_argument("--num", type=int, default=300)
    c.add_argument("--seed", type=int, default=0); c.add_argument("--model", default="open-athena/Grug-67B-A2B-Datakit-SFT-262K-2026.09.21")
    args = ap.parse_args()
    import collections
    import numpy as np
    from regenerate_token_rows import RowStore
    from transformers import AutoTokenizer

    tok = AutoTokenizer.from_pretrained(args.model)
    store = RowStore(args.dataset)
    idx = np.random.default_rng(args.seed).choice(int(store.num_rows * 0.999), size=args.num, replace=False)
    ok, why = 0, collections.Counter()
    examples = []
    for i in idx:
        ids, _ = store.get(int(i))
        good, reason = roundtrip_ok(tok, ids)
        ok += good
        if not good:
            why[reason.split(":")[0].split(" at")[0]] += 1
            if len(examples) < 5:
                examples.append((int(i), reason))
    print(f"round trip exact: {ok}/{len(idx)} = {ok / len(idx):.1%}; failures by kind: {dict(why)}")
    for e in examples:
        print("  example:", e)


if __name__ == "__main__":
    main()
