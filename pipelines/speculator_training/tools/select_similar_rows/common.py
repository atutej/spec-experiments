"""Shared helpers: what text of a row is embedded, and how. Used by embed_rows.py (run in the `embed` env).

Both sides embed `system text + "\n\n" + first user text` (no tool definitions, no later turns), left-truncated to WINDOW embedder tokens,
behind the symmetric EmbeddingGemma 2 task prefix. RL side: the prompt's leading system message (if any) and its first user message.
Datakit side: the row's token ids are cut at the end of the first user turn; the first system header (reasoning mode "Reasoning: /think" plus the
tools block, regenerated by the chat template, see tools/rows_to_messages.py) is skipped and any later system header is the real system prompt.
"""
import numpy as np

MODEL = "google/embeddinggemma-2"
PREFIX = "task: sentence similarity | query: "
WINDOW = 8192
TARGET = "open-athena/Grug-67B-A2B-Datakit-SFT-262K-2026.09.21"   # tokenizer of the Datakit rows
MAX_USER_IDS, MAX_SYSTEM_IDS = 8192, 4096                          # decode at most this many Grug ids; the exact cut is made on the embedder's tokens


def load_tokenizers():
    from transformers import AutoTokenizer
    return AutoTokenizer.from_pretrained(TARGET), AutoTokenizer.from_pretrained(MODEL)


def special_ids(gt):
    return {"h0": gt.convert_tokens_to_ids("<|start_header_id|>"), "h1": gt.convert_tokens_to_ids("<|end_header_id|>"),
            "eot": gt.convert_tokens_to_ids("<|eot_id|>"), "user": gt.encode("user", add_special_tokens=False)[0],
            "system": gt.encode("system", add_special_tokens=False)[0]}


def datakit_first_turn(ids: np.ndarray, gt, sp) -> tuple[str, str] | None:
    """(system text, first user text) of one Datakit row (ids: int64 numpy view), or None if it has no first user header."""
    heads = np.flatnonzero(ids == sp["h0"])
    heads = heads[(heads + 2 < len(ids))]
    heads = heads[ids[heads + 2] == sp["h1"]]                      # real role headers: <|start_header_id|> role <|end_header_id|>
    user_at = [h for h in heads if ids[h + 1] == sp["user"]]
    if not user_at:
        return None
    u = int(user_at[0])
    eots = np.flatnonzero(ids[u + 3:] == sp["eot"])
    u_end = u + 3 + (int(eots[0]) if len(eots) else len(ids) - u - 3)
    user = gt.decode(ids[max(u + 3, u_end - MAX_USER_IDS):u_end].tolist(), skip_special_tokens=False).lstrip("\n")
    system, seen = [], 0
    for h in heads:
        h = int(h)
        if h >= u:
            break
        if ids[h + 1] != sp["system"]:
            continue
        e = np.flatnonzero(ids[h + 3:u] == sp["eot"])
        end = h + 3 + (int(e[0]) if len(e) else u - h - 3)
        text = gt.decode(ids[max(h + 3, end - MAX_SYSTEM_IDS):end].tolist(), skip_special_tokens=False).strip("\n")
        if seen == 0 and text.startswith("Reasoning:"):
            seen += 1                                              # the auxiliary header: reasoning mode and tools, not a system prompt
            continue
        seen += 1
        if text:
            system.append(text)
    return "\n\n".join(system), user


def rl_first_turn(messages) -> tuple[str, str]:
    """(system text, first user text) of one RL prompt (a list of {"role", "content"} dicts; content may be None)."""
    system, user = "", ""
    for m in messages:
        if m["role"] == "system" and not user:
            system = m["content"] or ""
        elif m["role"] == "user":
            user = m["content"] or ""
            break
    return system, user


def join_text(system: str, user: str) -> str:
    return f"{system}\n\n{user}" if system else user


def clip_left(texts, et, window=WINDOW):
    """Prefix each text and keep its last tokens so the whole input is at most `window` embedder tokens (BOS/EOS margin 8)."""
    keep = window - len(et(PREFIX, add_special_tokens=False)["input_ids"]) - 8
    out, ncut = [], 0
    for text, ids in zip(texts, et(texts, add_special_tokens=False)["input_ids"]):
        if len(ids) > keep:
            text, ncut = et.decode(ids[-keep:]), ncut + 1
        out.append(PREFIX + text)
    return out, ncut


def load_embedder(device):
    import torch
    from sentence_transformers import SentenceTransformer
    model = SentenceTransformer(MODEL, device=device, model_kwargs={"torch_dtype": torch.bfloat16})
    model.max_seq_length = WINDOW
    return model


def model_revision():
    from huggingface_hub import snapshot_download
    return snapshot_download(MODEL, allow_patterns=["config.json"]).rstrip("/").split("/")[-1]
